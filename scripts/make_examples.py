def _find_font():
    candidates = [
        "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
        "/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf",
        "/System/Library/Fonts/Supplemental/Arial.ttf",
        "C:/Windows/Fonts/arial.ttf",
    ]
    for p in candidates:
        if os.path.exists(p):
            return p
    return None


def make_pdf():
    font_path = _find_font()
    path = os.path.join(EXAMPLES, "trudovoy_dogovor.pdf")
    doc = SimpleDocTemplate(path, pagesize=A4, topMargin=2 * cm, bottomMargin=2 * cm)
    styles = getSampleStyleSheet()

    if font_path:
        pdfmetrics.registerFont(TTFont("BaseFont", font_path))
        addMapping("BaseFont", 0, 0, "BaseFont")
        styles["BodyText"].fontName = "BaseFont"
        styles["Title"].fontName = "BaseFont"
    else:
        # Латинский fallback: кириллица из sysmono есть не везде, но файл создастся
        print("Шрифт для кириллицы не найден — PDF может отобразиться с искажениями.")

    flow = [Paragraph(LABOR_CONTRACT[0], styles["Title"]), Spacer(1, 12)]
    for line in LABOR_CONTRACT[1:]:
        if line and (line[0].isdigit() or line.startswith("г.") or line.startswith("ООО") or line.startswith("Работник:")):
            flow.append(Paragraph(line, styles["BodyText"]))
            flow.append(Spacer(1, 6))
        else:
            flow.append(Paragraph(line, styles["BodyText"]))
    doc.build(flow)
    print("PDF:", path)


def make_docx():
    path = os.path.join(EXAMPLES, "pravila_otpuskov.docx")
    doc = Document()
    for i, line in enumerate(VACATION_RULES):
        if i == 0:
            doc.add_heading(line, level=0)
        elif line and line[0].isdigit():
            doc.add_heading(line, level=1)
        else:
            doc.add_paragraph(line)
    doc.save(path)
    print("DOCX:", path)


